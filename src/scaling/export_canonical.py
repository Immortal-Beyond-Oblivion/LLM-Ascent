"""Export the canonical Act 5 checkpoints into a TRACKED, self-contained form.

Why this exists
---------------
``artifacts/`` is git-ignored, so the canonical models used for every Act 5
measurement were local-only: clearing the directory would cost ~3.4 h of
retraining (1.5M + 2.6M + 6.3M) and the figures in ``report/figures/`` could not
be regenerated by a reader. The whole premise of the project is that a claim can
be checked, so the weights ship with the claims.

What is saved
-------------
``model_state`` ONLY — no optimizer state, which would roughly triple the size
and is worthless for reproducing inference or figures. Model *config* is saved
alongside because the raw training checkpoints do not carry it. Float32 is kept
rather than float16: halving the file is not worth changing the numbers, and
these files exist so a reader can regenerate the report exactly.

Usage:
    python -m src.scaling.export_canonical
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
from pathlib import Path

import torch

CANONICAL = [("1.5M", 42, 7500), ("2.6M", 42, 12960), ("6.3M", 42, 30720)]
SOURCE_ROOT = Path("artifacts/scaling/checkpoints")
OUT_ROOT = Path("checkpoints/canonical")
TOKENIZER_SRC = Path("artifacts/scaling/tokenizer.json")
MANIFEST_SRC = Path("artifacts/scaling/manifest.json")


def _build_config(rung: str, vocab_size: int, context_length: int) -> dict:
    """Architecture of the canonical models, matching src/scaling/ladder.py.

    num_kv_heads=8 and window_size=0 because the canonical set is the plain
    multi-head baseline; the MQA/GQA/SWA variants are swept separately and are
    not part of the pinned set.
    """
    from src.scaling.ladder import ASPECT_LADDER

    dim, layers = ASPECT_LADDER[rung]
    return {
        "vocabulary_size": vocab_size,
        "context_length": context_length,
        "embedding_dim": dim,
        "num_heads": 8,
        "num_kv_heads": 8,
        "window_size": 0,
        "num_layers": layers,
        "dropout": 0.0,
        "normalization": "layernorm",
    }


def export(out_root: Path = OUT_ROOT) -> None:
    from src.model.gpt import GPTConfig, MiniGPT

    manifest = json.loads(MANIFEST_SRC.read_text(encoding="utf-8"))
    vocab_size = manifest["tokenizer_vocab_size"]
    context_length = manifest.get("context_length", 128)

    out_root.mkdir(parents=True, exist_ok=True)
    index = []

    for rung, seed, step in CANONICAL:
        src = SOURCE_ROOT / rung / f"seed{seed}" / "checkpoint.pt"
        if not src.exists():
            raise FileNotFoundError(f"missing source checkpoint: {src}")
        payload = torch.load(src, map_location="cpu", weights_only=False)

        if payload["completed_steps"] != step:
            raise ValueError(
                f"{rung}: checkpoint at step {payload['completed_steps']}, expected {step}")

        config = _build_config(rung, vocab_size, context_length)

        # Reload through the public constructor so we verify the exported file
        # actually reconstructs a working model rather than merely saving bytes.
        model = MiniGPT(GPTConfig(**config))
        model.load_state_dict(payload["model_state"])
        model.eval()

        state = {k: v.clone() for k, v in model.state_dict().items()}
        final_loss = payload["history"][-1]["val_loss"]

        dest_dir = out_root / rung
        dest_dir.mkdir(parents=True, exist_ok=True)
        dest = dest_dir / "model.pt"
        torch.save({
            "model_state": state,
            "model_config": config,
            "rung": rung,
            "seed": seed,
            "completed_steps": step,
            "val_loss": final_loss,
            "note": "model_state only; no optimizer state. "
                    "Recreated from artifacts/scaling/checkpoints.",
        }, dest)

        digest = hashlib.sha256(dest.read_bytes()).hexdigest()
        size_mb = dest.stat().st_size / 1e6
        n_params = sum(v.numel() for v in state.values())
        print(f"{rung}: {size_mb:6.1f} MB  {n_params:>10,} params  "
              f"val_loss={final_loss:.4f}  sha256={digest[:16]}...")
        index.append({
            "rung": rung, "seed": seed, "completed_steps": step,
            "val_loss": final_loss, "non_embedding_params": model.non_embedding_params(),
            "parameters": n_params, "file": f"{rung}/model.pt",
            "size_mb": round(size_mb, 2), "sha256": digest,
        })

    tokenizer_dest = out_root / "tokenizer.json"
    shutil.copy2(TOKENIZER_SRC, tokenizer_dest)
    print(f"tokenizer: {tokenizer_dest.stat().st_size / 1e6:.2f} MB")

    (out_root / "INDEX.json").write_text(json.dumps({
        "description": "Canonical Act 5 checkpoints (1.5M / 2.6M / 6.3M), "
                       "model weights only, float32.",
        "architecture": "MiniGPT, learned absolute positions, LayerNorm, "
                        "8 heads, 8 KV heads, no sliding window",
        "tokenizer": "tokenizer.json (BPE, trained on the C4 train split)",
        "usage": ".venv/bin/python -m src.scaling.export_canonical  # regenerate",
        "total_size_mb": round(sum(i["size_mb"] for i in index)
                               + tokenizer_dest.stat().st_size / 1e6, 2),
        "models": index,
    }, indent=2), encoding="utf-8")
    print(f"\nwrote {out_root}/INDEX.json")


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out-root", type=Path, default=OUT_ROOT)
    export(ap.parse_args().out_root)
